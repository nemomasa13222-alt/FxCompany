def fmt_dt(dt):
    wd = WEEKDAY_JP[dt.weekday()]
    return f"{dt.year}/{dt.month:02d}/{dt.day:02d}({wd}) {dt.hour:02d}:{dt.minute:02d}"


def build_rows(start_no):
    rows = []
    no = start_no
    for date_str, name, et_time, period in EVENTS:
        et_h, et_m = map(int, et_time.split(":"))
        et_dt = datetime.strptime(date_str, "%Y-%m-%d").replace(hour=et_h, minute=et_m)
        mt4_dt = et_dt + timedelta(hours=7)   # EDT(UTC-4) -> MT4夏EEST(UTC+3)
        jst_dt = et_dt + timedelta(hours=13)  # EDT(UTC-4) -> JST(UTC+9)
        us_date_str = f"{et_dt.year}/{et_dt.month:02d}/{et_dt.day:02d}({WEEKDAY_JP[et_dt.weekday()]})"
        rows.append({
            "No.": no,
            "米国日付": us_date_str,
            "指標名": name,
            "MT4時間": fmt_dt(mt4_dt),
            "重要度": IMPORTANCE[name],
            "対象期間": period,
            "発表時刻(ET)": et_time,
            "日本時間(JST)": fmt_dt(jst_dt),
            "備考": "米夏時間(EDT) / MT4+3",
        })
        no += 1
    return rows


def main():
    xls = pd.ExcelFile(SRC)
    df_main = xls.parse(xls.sheet_names[0])
    df_legend = xls.parse(xls.sheet_names[1])

    start_no = int(df_main["No."].max()) + 1
    new_rows = build_rows(start_no)
    df_new = pd.DataFrame(new_rows)

    df_out = pd.concat([df_main, df_new], ignore_index=True)

    with pd.ExcelWriter(SRC, engine="openpyxl") as writer:
        df_out.to_excel(writer, sheet_name=xls.sheet_names[0], index=False)
        df_legend.to_excel(writer, sheet_name=xls.sheet_names[1], index=False)

    print(f"追記: {len(new_rows)}件（No.{start_no}〜{start_no + len(new_rows) - 1}）")
    print(f"合計: {len(df_out)}件")
    print(f"→ {SRC}")


if __name__ == "__main__":
    main()
